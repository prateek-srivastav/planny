"""Exchange rates via Frankfurter (ECB reference rates, keyless).

Rates are fetched, never generated by a model. Covers ~30 major currencies; an unsupported
pair raises a non-retryable `ToolFailure`, which the plan records as degraded data.
"""

import httpx

from app.graph.state import ExchangeRate
from app.tools.collector import ToolFailure


async def fetch_rate(client: httpx.AsyncClient, base: str, quote: str) -> ExchangeRate:
    base, quote = base.strip().upper(), quote.strip().upper()
    if base == quote:
        return ExchangeRate(base=base, quote=quote, rate=1.0, date=None)
    resp = await client.get(
        "https://api.frankfurter.dev/v1/latest", params={"base": base, "symbols": quote}
    )
    code = resp.status_code
    if code in (404, 422):
        raise ToolFailure(
            f"exchange_rate: {base}->{quote} is not available from the ECB rate source",
            retryable=False,
        )
    if code >= 400:
        raise ToolFailure(f"exchange_rate: frankfurter returned HTTP {code}", retryable=code >= 500)
    data = resp.json()
    rate = (data.get("rates") or {}).get(quote)
    if rate is None:
        raise ToolFailure(f"exchange_rate: no {base}->{quote} rate returned", retryable=False)
    return ExchangeRate(base=base, quote=quote, rate=float(rate), date=data.get("date"))
